/** Flattens every request's articles into one row per article, carrying the parent request's context along. */
/** Derives a stable org-wide "USRM-######" project reference from the internal REX request id. */
function toProjectId(requestId: string): string {
  const numericPart = Number(requestId.replace(/\D/g, '')) || 0;
  return `USRM-${100000 + numericPart}`;
}

export function getAllArticleRows(): RexArticleRow[] {
  return rexRequests.flatMap((request) =>
    request.articles.map((article) => ({
      ...article,
      rowId: `${request.id}-${article.id}`,
      requestId: request.id,
      projectId: toProjectId(request.id),
      storeNumber: request.storeNumber,
      storeName: request.storeName,
      submittedBy: request.submittedBy,
      submittedAt: request.submittedAt,
      director: request.director,
      srDirector: request.srDirector,
      possessionDate: request.possessionDate,
      grandOpeningDate: request.grandOpeningDate,
      reviewedBy: request.reviewedBy,
      reviewedAt: request.reviewedAt,
    }))
  );
}

function findArticleByRowId(rowId: string): RexArticle | undefined {
  for (const request of rexRequests) {
    const article = request.articles.find((a) => `${request.id}-${a.id}` === rowId);
    if (article) return article;
  }
  return undefined;
}

/** Mutates the underlying article's decision in place (this is an in-memory demo data store, not a real API). */
export function decideArticleRow(rowId: string, decision: ArticleDecision, reason?: string): RexArticle | undefined {
  const article = findArticleByRowId(rowId);
  if (!article) return undefined;
  article.decision = decision;
  if ((decision === 'rejected' || decision === 'cancelled') && reason) {
    article.decisionReason = reason;
  }
  return article;
}

/** Mutates the underlying article's finalized quantity in place. */
export function updateArticleRowQty(rowId: string, newQty: number): RexArticle | undefined {
  const article = findArticleByRowId(rowId);
  if (!article) return undefined;
  article.newQty = newQty;
  return article;
}
