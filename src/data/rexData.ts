export type ArticleDecision = 'pending' | 'accepted' | 'rejected' | 'cancelled';

export interface RexArticle {
  id: string;
  articleNumber: string;
  articleName: string;
  departmentNumber: string;
  departmentName: string;
  asIsQty: number;
  requestedQty: number;
  newQty: number;
  unitCost: number;
  deliveryType: string;
  deliveryDate: string;
  tentativeSapSubmissionDate: string;
  reason: string;
  decision: ArticleDecision;
  decisionReason?: string;
  /** Resolved fixture photo — optional; rows without one fall back to a generic thumbnail placeholder. */
  imageUrl?: string;
  /** Meaningful a11y description of imageUrl's contents — required whenever imageUrl is set. */
  imageAlt?: string;
}

export interface RexRequest {
  id: string;
  storeNumber: string;
  storeName: string;
  submittedBy: string;
  director: string;
  srDirector: string;
  submittedAt: string;
  reviewedBy?: string;
  reviewedAt?: string;
  possessionDate: string;
  grandOpeningDate: string;
  articles: RexArticle[];
}

/** A single article flattened with its parent request's context — the unit the Inbox table renders one row per. */
export interface RexArticleRow extends RexArticle {
  /** Stable composite key (`${requestId}-${article.id}`) — article ids repeat across requests. */
  rowId: string;
  requestId: string;
  /** Org-wide project reference (e.g. "USRM-110245"), distinct from the internal REX request id. */
  projectId: string;
  storeNumber: string;
  storeName: string;
  submittedBy: string;
  submittedAt: string;
  director: string;
  srDirector: string;
  possessionDate: string;
  grandOpeningDate: string;
  reviewedBy?: string;
  reviewedAt?: string;
}

export type InboxSection = 'pending' | 'rejected' | 'cancelled';

export function getIncrementalUnits(article: RexArticle): number {
  return Math.max(article.newQty - article.asIsQty, 0);
}

export function getIncreasePercent(article: RexArticle): number {
  if (article.asIsQty === 0) return article.newQty > 0 ? 100 : 0;
  return Math.round(((article.newQty - article.asIsQty) / article.asIsQty) * 100);
}

export function formatDateTime(iso: string): string {
  return new Intl.DateTimeFormat('en-US', {
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  }).format(new Date(iso));
}

export function formatDate(iso: string): string {
  return new Intl.DateTimeFormat('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  }).format(new Date(iso));
}

